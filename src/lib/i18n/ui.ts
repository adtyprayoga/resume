export type UiStringKey = keyof (typeof strings)['en']

export interface UiMessage {
  messageKey: UiStringKey
  messageParams?: Record<string, string | number>
}

export const t = (locale: Locale, key: UiStringKey, params?: UiMessage['messageParams']): string =>
  strings[locale][key].replace(/\{(\w+)\}/g, (token, name: string) => String(params?.[name] ?? token))

export const translatedMessage = (
  locale: Locale,
  metadata: Partial<UiMessage> | null | undefined,
  fallback: string,
): string => metadata?.messageKey ? t(locale, metadata.messageKey, metadata.messageParams) : fallback
