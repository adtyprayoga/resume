import { beforeEach, expect, it, vi } from 'vitest'
import { render, screen, fireEvent } from '@testing-library/svelte'
import userEvent from '@testing-library/user-event'
import ImportDialog from '../ImportDialog.svelte'
import App from '../../App.svelte'
import { prefs } from '$lib/state/preferences.svelte'
import { editing } from '$lib/state/editing.svelte'
beforeEach(() => { localStorage.clear(); prefs.uiLocale = 'en'; editing.reset(); vi.unstubAllGlobals() })
it('opens a format menu, closes export, and selects JSON before opening a dialog', async () => {
  render(App)
  const user = userEvent.setup()
  await user.click(screen.getByRole('button', { name: 'Export' }))
  await user.click(screen.getByRole('button', { name: 'Upload' }))
  expect(screen.queryByRole('menu', { name: 'Export' })).toBeNull()
  expect(screen.queryByRole('dialog')).toBeNull()
  await user.click(screen.getByRole('menuitem', { name: 'Upload JSON' }))
  expect(screen.getByRole('dialog', { name: 'Import resume JSON' })).toBeInTheDocument()
})
it('shows only selected PDF format and an explicit picker without uploading', async () => {
  const fetch = vi.fn(); vi.stubGlobal('fetch', fetch)
  render(ImportDialog, { onClose() {}, pdfImport: true, format: 'pdf' })
  expect(screen.queryByLabelText('Paste JSON')).toBeNull()
  expect(screen.getByRole('button', { name: 'Choose PDF' })).toBeInTheDocument()
  await userEvent.setup().upload(screen.getByLabelText('Resume PDF'), new File(['%PDF'], 'resume.pdf', { type: 'application/pdf' }))
  expect(screen.getByText('resume.pdf')).toBeInTheDocument()
  expect(fetch).not.toHaveBeenCalled()
  await userEvent.setup().click(screen.getByRole('button', { name: 'Remove file' }))
  expect(screen.getByRole('button', { name: 'Convert PDF' })).toBeDisabled()
})
it('rejects multiple dropped files and contradictory PDF MIME before conversion', async () => {
  render(ImportDialog, { onClose() {}, pdfImport: true, format: 'pdf' })
  const zone = screen.getByRole('group', { name: /Resume PDF:/ })
  await fireEvent.drop(zone, { dataTransfer: { files: [new File(['a'], 'a.pdf'), new File(['b'], 'b.pdf')] } })
  expect(screen.getByRole('alert')).toHaveTextContent('Choose one file at a time.')
  await fireEvent.change(screen.getByLabelText('Resume PDF'), { target: { files: [new File(['a'], 'a.pdf', { type: 'image/png' })] } })
  expect(screen.getByRole('alert')).toHaveTextContent('Choose a PDF file with a matching file type.')
})

it('retains only JSON when PDF is disabled even if requested directly', () => {
  render(ImportDialog, { onClose() {}, pdfImport: false, format: 'pdf' })
  expect(screen.queryByLabelText('Resume PDF')).toBeNull()
  expect(screen.getByRole('button', { name: 'Choose JSON' })).toBeInTheDocument()
})
it('supports keyboard upload menu navigation and restores its trigger on Escape', async () => {
  render(App)
  const user = userEvent.setup()
  const upload = screen.getByRole('button', { name: 'Upload' })
  upload.focus()
  await user.keyboard('{ArrowUp}')
  expect(screen.getByRole('menuitem', { name: 'Upload JSON' })).toHaveFocus()
  expect(screen.queryByRole('menuitem', { name: 'Upload PDF' })).toBeNull()
  expect(editing.suspended).toBe(false)
  await user.keyboard('{Escape}')
  expect(upload).toHaveFocus()
  expect(screen.queryByRole('menu')).toBeNull()
})
it('allows same-file retry, changing and removing a PDF without uploading', async () => {
  const fetch = vi.fn(); vi.stubGlobal('fetch', fetch)
  render(ImportDialog, { onClose() {}, pdfImport: true, format: 'pdf' })
  const input = screen.getByLabelText('Resume PDF') as HTMLInputElement
  const user = userEvent.setup()
  const file = new File(['%PDF'], 'repeat.pdf')
  await fireEvent.change(input, { target: { files: [file] } })
  expect(input.value).toBe('')
  expect(screen.getByText('repeat.pdf')).toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: 'Remove file' }))
  await fireEvent.change(input, { target: { files: [file] } })
  expect(screen.getByText('repeat.pdf')).toBeInTheDocument()
  await fireEvent.change(input, { target: { files: [new File(['%PDF'], 'changed.pdf', { type: 'application/pdf' })] } })
  expect(screen.queryByText('repeat.pdf')).toBeNull()
  expect(screen.getByText('changed.pdf')).toBeInTheDocument()
  expect(fetch).not.toHaveBeenCalled()
})
it('rejects an oversized PDF locally and accepts its exact byte limit', async () => {
  render(ImportDialog, { onClose() {}, pdfImport: true, format: 'pdf' })
  const input = screen.getByLabelText('Resume PDF')
  const file = new File(['%PDF'], 'large.pdf', { type: 'application/pdf' })
  Object.defineProperty(file, 'size', { value: 10 * 1024 * 1024 + 1, configurable: true })
  await fireEvent.change(input, { target: { files: [file] } })
  expect(screen.getByRole('alert')).toHaveTextContent('too large')
  expect(screen.getByRole('button', { name: 'Convert PDF' })).toBeDisabled()
  Object.defineProperty(file, 'size', { value: 10 * 1024 * 1024 })
  await fireEvent.change(input, { target: { files: [file] } })
  expect(screen.queryByRole('alert')).toBeNull()
  expect(screen.getByRole('button', { name: 'Convert PDF' })).toBeEnabled()
})
it('invalid multiple drops clear a previous actionable PDF selection', async () => {
  render(ImportDialog, { onClose() {}, pdfImport: true, format: 'pdf' })
  const zone = screen.getByRole('group', { name: /Resume PDF:/ })
  const pdf = new File(['a'], 'a.pdf', { type: 'application/pdf' })
  await fireEvent.drop(zone, { dataTransfer: { files: [pdf] } })
  expect(screen.getByRole('button', { name: 'Convert PDF' })).toBeEnabled()
  await fireEvent.drop(zone, { dataTransfer: { files: [pdf, pdf] } })
  expect(screen.getByRole('button', { name: 'Convert PDF' })).toBeDisabled()
  expect(screen.queryByText('a.pdf')).toBeNull()
})
it('shows a readable size and marks the drop area while dragging', async () => {
  render(ImportDialog, { onClose() {}, pdfImport: true, format: 'pdf' })
  const zone = screen.getByRole('group', { name: /Resume PDF:/ })
  await fireEvent.dragEnter(zone, { dataTransfer: { files: [] } })
  expect(zone).toHaveClass('dragging')
  await fireEvent.dragLeave(zone, { dataTransfer: { files: [] } })
  expect(zone).not.toHaveClass('dragging')
  const file = new File(['%PDF'], 'sized.pdf', { type: 'application/pdf' })
  Object.defineProperty(file, 'size', { value: 1536 })
  await fireEvent.drop(zone, { dataTransfer: { files: [file] } })
  expect(zone).not.toHaveClass('dragging')
  expect(screen.getByText('1.5 kB')).toBeInTheDocument()
})
